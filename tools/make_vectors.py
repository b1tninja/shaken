"""Regenerate tests/vectors.py: the test vectors this project owns.

Provenance: none of these come from an RFC. RFC 8225 Appendix A is not usable for signature
verification (its signature verifies under neither printed key, and its two printed keys are not
a pair; tests/test_rfc_findings.py pins that), so this project writes its own.

* The private key is a fixed P-256 scalar chosen here and is a TEST KEY: never use it for anything.
* ES256 signatures are deterministic ECDSA (RFC 6979), so the tokens regenerate byte for byte.
* The certificate is signed with `cryptography`, whose certificate builder is not deterministic;
  regenerating changes its bytes and its signature, never its contents.
* The TNAuthList extension value is encoded by hand in this file, from RFC 8226 Appendix A
  (EXPLICIT TAGS), independently of shaken/tnauth.py, so the parser is tested against bytes it
  did not produce.

Run from the project directory:  python tools/make_vectors.py > tests/vectors.py
"""

from __future__ import annotations

import datetime
import sys

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import NameOID, ObjectIdentifier

sys.path.insert(0, ".")
sys.path.insert(0, "../asn1core")

from shaken import claims, jws, passport

SCALAR = (
    0x1C0FFEE5EED0F00DBADC0DE5EED5ABCDEF1234567890ABCDEF1234567890AB11 % (jws.P256_ORDER - 1) + 1
)


def tlv(tag: int, body: bytes) -> bytes:
    assert len(body) < 128  # noqa: S101 - a generator, not package code
    return bytes([tag, len(body)]) + body


def ia5(text: str) -> bytes:
    return tlv(0x16, text.encode("ascii"))


def tn_auth_list() -> bytes:
    spc = tlv(0xA0, ia5("1234"))  # [0] ServiceProviderCode
    rng = tlv(0xA1, tlv(0x30, ia5("2125550100") + tlv(0x02, bytes([100]))))  # [1] range, count 100
    one = tlv(0xA2, ia5("12155551212"))  # [2] TelephoneNumber
    return tlv(0x30, spc + rng + one)


def main() -> None:
    key = ec.derive_private_key(SCALAR, ec.SECP256R1())
    signer = jws.Es256Signer(key)
    pem = key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    ).decode()
    x5u = "https://cert.example.org/passport.cer"
    payload = claims.shaken_claims(
        "+1 (215) 555-1212",
        ["12155550131"],
        iat=1443208345,
        attest="A",
        origid="123e4567-e89b-12d3-a456-426655440000",
    )
    token = passport.create(payload, claims.shaken_header(x5u), signer)

    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "shaken test signer")])
    start = datetime.datetime(2026, 1, 1, tzinfo=datetime.UTC)
    cert = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(0x5EED)
        .not_valid_before(start)
        .not_valid_after(start + datetime.timedelta(days=3650))
        .add_extension(
            x509.UnrecognizedExtension(ObjectIdentifier("1.3.6.1.5.5.7.1.26"), tn_auth_list()),
            critical=False,
        )
        .sign(key, hashes.SHA256())
    )
    print('"""Generated by tools/make_vectors.py. Do not edit; read that file for provenance."""')
    print()
    print("# ruff: noqa: S105")
    print()
    print("from __future__ import annotations")
    print()
    print(f"TEST_KEY_PEM = {pem!r}")
    print(f"X5U = {x5u!r}")
    print(f"SHAKEN_TOKEN = {token!r}")
    print(f"TN_AUTH_LIST_DER = {tn_auth_list().hex()!r}")
    print(f"CERT_PEM = {cert.public_bytes(serialization.Encoding.PEM).decode()!r}")


if __name__ == "__main__":
    main()
